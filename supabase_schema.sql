create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room text not null,
  author text not null,
  text text not null default '',
  attachment_url text,
  attachment_name text,
  created_at timestamptz not null default now()
);

alter table public.messages
  add column if not exists room text;

update public.messages
set room = 'main'
where room is null;

alter table public.messages
  alter column room set default 'main',
  alter column room set not null;

create index if not exists messages_room_created_at_idx
  on public.messages (room, created_at);

alter publication supabase_realtime add table public.messages;

alter table public.messages enable row level security;

drop policy if exists "Public users can read messages" on public.messages;
create policy "Public users can read messages"
  on public.messages for select to anon, authenticated using (true);

drop policy if exists "Public users can send messages" on public.messages;
create policy "Public users can send messages"
  on public.messages for insert to anon, authenticated with check (true);

drop policy if exists "Public users can delete messages" on public.messages;
create policy "Public users can delete messages"
  on public.messages for delete to anon, authenticated using (true);

insert into storage.buckets (id, name, public)
values ('attachments', 'attachments', true)
on conflict (id) do update set public = true;

drop policy if exists "Public users can upload attachments" on storage.objects;
create policy "Public users can upload attachments"
  on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'attachments');

drop policy if exists "Public users can read attachments" on storage.objects;
create policy "Public users can read attachments"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'attachments');