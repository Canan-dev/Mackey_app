create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  room text not null default 'main',
  author text not null,
  text text not null default '',
  attachment_url text,
  attachment_name text,
  created_at timestamptz not null default now()
);

create index if not exists messages_room_created_at_idx
  on public.messages (room, created_at);

-- Enable Realtime
alter publication supabase_realtime add table public.messages;

-- Explicit permissions for anon and authenticated users
grant usage on schema public to anon, authenticated;
grant all on table public.messages to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- Row Level Security (RLS) policies
alter table public.messages enable row level security;

drop policy if exists "Allow public select" on public.messages;
create policy "Allow public select"
  on public.messages for select to anon, authenticated using (true);

drop policy if exists "Allow public insert" on public.messages;
create policy "Allow public insert"
  on public.messages for insert to anon, authenticated with check (true);

drop policy if exists "Allow public update" on public.messages;
create policy "Allow public update"
  on public.messages for update to anon, authenticated using (true) with check (true);

drop policy if exists "Allow public delete" on public.messages;
create policy "Allow public delete"
  on public.messages for delete to anon, authenticated using (true);

-- Storage bucket setup for attachments
insert into storage.buckets (id, name, public)
values ('attachments', 'attachments', true)
on conflict (id) do update set public = true;

drop policy if exists "Public users can upload attachments" on storage.objects;
create policy "Public users can upload attachments"
  on storage.objects for insert to anon, authenticated
  with check (bucket_id = 'attachments');

drop policy if exists "Public users can read attachments" on storage.objects;
create policy "Public users can read attachments"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'attachments');
